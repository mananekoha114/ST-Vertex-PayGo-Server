// Builds vendor/isomorphic-git.bundle.cjs from the pinned devDependencies.
//
// The bundle is committed because users must be able to install and update the
// plugin without npm. Run this only after changing the pinned versions, then
// commit the rebuilt file. `--check` rebuilds into memory and fails when the
// committed bundle no longer matches, so a stale artifact cannot pass review.

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'scripts', 'vendor-entry.mjs');
const target = path.join(root, 'vendor', 'isomorphic-git.bundle.cjs');
const noticesTarget = path.join(root, 'vendor', 'THIRD_PARTY_NOTICES.txt');
const check = process.argv.includes('--check');

const result = await build({
    entryPoints: [entry],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    external: ['node:*'],
    legalComments: 'inline',
    metafile: true,
    banner: {
        js: '/* Generated by scripts/build-vendor.mjs. Do not edit. '
            + 'Source: isomorphic-git and isomorphic-git/http/node at the versions in package.json. */',
    },
    write: false,
});

const [produced] = result.outputFiles;
// npm packages sometimes omit a separate license file or keep additional
// notices in source headers. Preserve both from the inputs actually bundled.
async function collectNotices(inputs) {
    const packages = new Map();
    for (const input of Object.keys(inputs).sort()) {
        const source = path.resolve(input);
        if (!source.includes(`${path.sep}node_modules${path.sep}`)) continue;
        let directory = path.dirname(source);
        let pkg;
        while (directory !== path.dirname(directory)) {
            try {
                const candidate = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
                if (candidate.name && candidate.version) { pkg = candidate; break; }
            } catch (error) {
                if (error.code !== 'ENOENT') throw error;
            }
            directory = path.dirname(directory);
        }
        if (!pkg) throw new Error(`Cannot identify bundled package: ${input}`);
        let record = packages.get(directory);
        if (!record) {
            record = { pkg, directory, headers: new Map() };
            packages.set(directory, record);
        }
        const text = await readFile(source, 'utf8');
        const header = text.replace(/^\s*['"]use strict['"];?/u, '')
            .match(/^(?:\s*(?:\/\*[\s\S]*?\*\/|\/\/[^\n]*(?:\n|$)))+/u)?.[0].trim();
        if (header && /copyright|\(C\)/iu.test(header)) record.headers.set(header, path.relative(directory, source));
    }
    const sections = ['Third-party notices for isomorphic-git.bundle.cjs. Generated by scripts/build-vendor.mjs.'];
    for (const { pkg, directory, headers } of [...packages.values()].sort((a, b) => a.pkg.name < b.pkg.name ? -1 : 1)) {
        sections.push(`\n${pkg.name}@${pkg.version}\nLicense: ${pkg.license}\n${'='.repeat(72)}`);
        const files = (await readdir(directory)).filter(name => /^(?:licen[cs]e|copying|notice)(?:[.-]|$)/iu.test(name)).sort();
        for (const file of files) sections.push(`${file}:\n${(await readFile(path.join(directory, file), 'utf8')).trim()}`);
        for (const [header, file] of headers) sections.push(`${file} (source header):\n${header}`);
        if (pkg.name === 'clean-git-ref' && files.length === 0) {
            // clean-git-ref@2.0.1 declares Apache-2.0 but ships no license file.
            // crc-32, also bundled, ships the complete standard license text.
            sections.push(`Author: ${pkg.author}\nSource: ${pkg.repository.url}\nApache-2.0 text (from crc-32/LICENSE):\n${(await readFile(path.join(root, 'node_modules/crc-32/LICENSE'), 'utf8')).trim()}`);
        } else if (files.length === 0 && headers.size === 0) {
            throw new Error(`No license text found for bundled package ${pkg.name}.`);
        }
    }
    // isomorphic-git also contains an attributed LGPL path implementation.
    // Its inline notice remains in the bundle. The SPDX LGPL text includes GPL.
    if (!result.outputFiles[0].text.includes('SPDX-License-Identifier: LGPL-3.0-or-later')) {
        throw new Error('Review isomorphic-git embedded licenses after changing its version.');
    }
    sections.push('isomorphic-git embedded path implementation: see its inline @zenfs/core/path notice.\nUnminified source is distributed in the bundle; rebuild using package-lock.json and scripts/build-vendor.mjs.\nLicense texts: SPDX license-list-data at 31ba1a50e5397e00a304dbadc76531740e89ee48 (https://github.com/spdx/license-list-data).');
    sections.push(`LGPL-3.0-or-later (including GPL-3.0):\n${(await readFile(path.join(root, 'vendor/licenses/LGPL-3.0-or-later.txt'), 'utf8')).trim()}`);
    return sections.join('\n\n') + '\n';
}

if (produced === undefined) {
    console.error('ERROR: esbuild produced no output.');
    process.exitCode = 1;
} else if (check) {
    for (const [file, expected] of [[target, produced.text], [noticesTarget, await collectNotices(result.metafile.inputs)]]) {
        let committed = '';
        try { committed = await readFile(file, 'utf8'); }
        catch (error) {
            if (error.code !== 'ENOENT') throw error;
        }
        if (committed !== expected) {
            console.error(`ERROR: ${path.relative(root, file)} is stale. Run node scripts/build-vendor.mjs and commit the result.`);
            process.exitCode = 1;
        } else console.log(`${path.relative(root, file)} is current: ${expected.length} bytes.`);
    }
} else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, produced.text);
    await writeFile(noticesTarget, await collectNotices(result.metafile.inputs));
    console.log(`Wrote ${path.relative(root, target)}: ${produced.text.length} bytes.`);
}
